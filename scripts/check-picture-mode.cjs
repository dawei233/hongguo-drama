const assert = require('node:assert/strict');
const { mount } = require('./check-player-resume.cjs');
(async () => {
  const storage = new Map();
  const ui = mount({ local: true, storage, props: { portrait: true } });
  await ui.flush(); ui.metadata(); ui.media.currentTime = 37;
  const controls = () => ui.find(n => n.props.videoRef && n.props.onRateChange);
  const video = () => ui.find(n => n.type === 'video');
  assert.equal(controls().props.pictureMode, 'fit');
  const original = video().props;
  controls().props.onPictureModeChange('width'); ui.render();
  assert.equal(controls().props.pictureMode, 'width');
  assert.equal(ui.media.currentTime, 37);
  assert.equal(video().props.src, original.src);
  assert.equal(video().props.key, original.key);
  assert.equal(video().props.ref, original.ref);
  // 竖屏全屏现在是原生窗口全屏（nativeFullscreen 属性），不再是 onWindowFill 回调
  ui.props.nativeFullscreen = true; ui.render();
  assert.equal(controls().props.pictureMode, 'width');
  assert.equal(ui.media.currentTime, 37);
  ui.episode(2); await ui.flush(); ui.metadata();
  assert.equal(controls().props.pictureMode, 'width');
  ui.unmount();
  const reopened = mount({ local: true, storage, props: { setEpisodesOpen() {} } }); await reopened.flush();
  assert.equal(reopened.find(n => n.props.onPictureModeChange).props.pictureMode, 'width');
  reopened.find(n => n.props.onPictureModeChange).props.onPictureModeChange('fit'); reopened.unmount();
  const reset = mount({ local: true, storage, props: { setEpisodesOpen() {} } }); await reset.flush();
  assert.equal(reset.find(n => n.props.onPictureModeChange).props.pictureMode, 'fit'); reset.unmount();
  const other = mount({ local: true, storage: new Map([['hongguo:picture-mode:A', 'width']]), seriesId: 'B', props: { setEpisodesOpen() {} } }); await other.flush();
  assert.equal(other.find(n => n.props.onPictureModeChange).props.pictureMode, 'fit'); other.unmount();
  const broken = mount({ local: true, storage: { get() { throw Error('denied'); }, set() { throw Error('full'); } }, props: { setEpisodesOpen() {} } }); await broken.flush();
  broken.find(n => n.props.onPictureModeChange).props.onPictureModeChange('width'); broken.render();
  assert.equal(broken.find(n => n.props.onPictureModeChange).props.pictureMode, 'width');
  assert.ok(broken.find(n => n.children?.some(c => typeof c === 'string' && c.includes('未能保存')))); broken.unmount();
  console.log('PASS picture-mode default, persistence, progress/node, episode and portrait-fullscreen continuity');
})().catch(error => { console.error(error); process.exitCode = 1; });
